def main() -> None:
    os.makedirs(FIX, exist_ok=True)
    files = {
        "dup_master.ics": DUP_MASTER,
        "dup_override.ics": DUP_OVERRIDE,
        "orphan_override.ics": ORPHAN_OVERRIDE,
        "rid_out_of_count.ics": RID_OUT_OF_COUNT,
        "rid_skipped_day.ics": RID_SKIPPED_DAY,
        "exdate_conflict.ics": EXDATE_CONFLICT,
        "type_mismatch.ics": TYPE_MISMATCH,
        "bad_rrules.ics": BAD_RRULES,
        "unknown_props.ics": UNKNOWN_PROPS,
        "incomplete_override.ics": INCOMPLETE_OVERRIDE,
        "bad_until.ics": BAD_UNTIL,
        "eof_error.ics": EOF_ERROR,
    }
    for name, text in files.items():
        path = os.path.join(FIX, name)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
